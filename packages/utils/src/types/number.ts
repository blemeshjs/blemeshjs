import Long from "long";

/**
 * Represents an unsigned 8-bit integer.
 */
export type UInt8 = number;

/**
 * Represents a signed 8-bit integer.
 */
export type Int8 = number;

/**
 * Represents an unsigned 16-bit integer.
 */
export type UInt16 = number;

/**
 * Represents a signed 16-bit integer.
 */
export type Int16 = number;

/**
 * Represents an unsigned 32-bit integer.
 */
export type UInt32 = number;

/**
 * Represents a signed 32-bit integer.
 */
export type Int32 = number;

/**
 * Represents an unsigned 64-bit integer using bigint.
 */
export type UInt64 = Long;

/**
 * Represents a signed 64-bit integer using Long.
 */
export type Int64 = Long;

/**
 * Represents a 64-bit IEEE‑754 double-precision floating-point
 * (the same as JavaScript's built-in `number` type).
 */
export type Double = number;
